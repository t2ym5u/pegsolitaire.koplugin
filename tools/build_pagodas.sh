#!/bin/bash
# Rebuilds ../pagodas_data.lua: one build_pagodas.lua run per board:goal group,
# in parallel, then concatenated. Deterministic. About 5 min per group.
set -e
here="$(cd "$(dirname "$0")" && pwd)"
tmp="$(mktemp -d)"
groups=$(luajit "$here/build_pagodas.lua" --list)
i=0
for g in $groups; do
    i=$((i + 1))
    luajit "$here/build_pagodas.lua" "$g" > "$tmp/$(printf %03d $i).lua" 2> "$tmp/$(printf %03d $i).log" &
done
wait
out="$here/../pagodas_data.lua"
{
    echo "-- Pagoda functions per board:goal, generated by tools/build_pagodas.sh --"
    echo "-- do not edit by hand. One weight per hole (geometry.lua numbering); the"
    echo "-- solver re-checks every one before use."
    echo "return {"
    cat "$tmp"/*.lua
    echo "}"
} > "$out"
rm -rf "$tmp"
