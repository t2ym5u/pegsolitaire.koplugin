-- build_puzzles.lua — turns puzzles_src.lua into ../puzzles_data.lua: every
-- puzzle's start, goal hole and a solution found (and replayed) by solver.lua.
-- A puzzle the solver cannot finish is an error: nothing unsolvable ships.
-- Usage: luajit build_puzzles.lua [pagodas_data.lua] > ../puzzles_data.lua

local here = debug.getinfo(1, "S").source:sub(2):match("(.*[/\\])") or "./"
package.path = here .. "../?.lua;" .. here .. "?.lua;" .. package.path
local Geometry = require("geometry")
local Solver   = require("solver")
Solver.MEMO_CAP = 1e9

local src = dofile(os.getenv("PZ_SRC") or (here .. "puzzles_src.lua"))
local pagodas = {}
if arg[1] then pagodas = dofile(arg[1]) end

local function parsePic(geo, def)
    local pegs, goal = {}, nil
    for i = 1, geo.n do pegs[i] = 0 end
    for r, row in ipairs(def.pic) do
        for c = 1, #row do
            local ch = row:sub(c, c)
            if ch ~= " " then
                local i = Geometry.holeAt(geo, r - 1, c - 1)
                assert(i, def.id .. ": no hole at row " .. r .. " col " .. c)
                if ch == "o" or ch == "*" then pegs[i] = 1 end
                if ch == "*" or ch == "+" then goal = i end
            end
        end
    end
    local holes = 0
    for _, row in ipairs(def.pic) do holes = holes + #row:gsub(" ", "") end
    assert(holes == geo.n, def.id .. ": picture does not cover the board")
    return pegs, goal
end

-- Goals to try for a "search" puzzle: the vacancy, the centre, then the rest
-- by distance from the centre of the board.
local function candidates(geo, vac)
    local cx, cy = 0, 0
    for _, h in ipairs(geo.holes) do cx, cy = cx + h.x, cy + h.y end
    cx, cy = cx / geo.n, cy / geo.n
    local list = {}
    for i = 1, geo.n do list[i] = i end
    local function d(i) local h = geo.holes[i] return (h.x - cx) ^ 2 + (h.y - cy) ^ 2 end
    table.sort(list, function(a, b)
        if (a == vac) ~= (b == vac) then return a == vac end
        if d(a) ~= d(b) then return d(a) < d(b) end
        return a < b
    end)
    return list
end

local out, failed = {}, false
for _, def in ipairs(src) do
    local geo = assert(Geometry.get(def.board), def.id .. ": unknown board")
    local pegs, goal, vac
    if os.getenv("PZ_ONLY") and not def.id:find(os.getenv("PZ_ONLY")) then goto continue end
    if def.pic then
        -- No goal marked: the most central hole that works.
        pegs, goal = parsePic(geo, def)
    else
        pegs = {}
        for i = 1, geo.n do pegs[i] = 1 end
        vac = assert(Geometry.holeAt(geo, def.vacancy[1], def.vacancy[2]), def.id .. ": bad vacancy")
        pegs[vac] = 0
    end
    do
        if def.goal == "same" then
            goal = vac
        elseif type(def.goal) == "table" then
            goal = assert(Geometry.holeAt(geo, def.goal[1], def.goal[2]))
        end
        if not goal then
            for _, g in ipairs(candidates(geo, vac)) do
                if not Geometry.goalInClass(geo, pegs, g) then goto next_goal end
                local s = Solver.new(geo, g, pagodas[def.board .. ":" .. g])
                local st = s:solve(pegs, 30e6)
                io.stderr:write(string.format("  %s: goal %d -> %s\n", def.id, g, st))
                if st == "yes" then goal = g break end
                ::next_goal::
            end
            if not goal then
                io.stderr:write("UNSOLVABLE: " .. def.id .. " (no goal found)\n")
                failed = true
                goto continue
            end
        end
    end
    local t0 = os.clock()
    local s = Solver.new(geo, goal, pagodas[def.board .. ":" .. goal])
    local st, path, nodes = s:solve(pegs)
    io.stderr:write(string.format("%-16s %-9s goal %2d: %s, %d nodes, %.2fs\n",
        def.id, def.board, goal, st, nodes, os.clock() - t0))
    if st ~= "yes" then
        io.stderr:write("UNSOLVABLE: " .. def.id .. " (left out)\n")
        failed = true
        goto continue
    end
    assert(Solver.check(geo, pegs, goal, path), def.id .. ": solution does not replay")
    local sol = {}
    for _, m in ipairs(path) do
        sol[#sol + 1] = geo.A[m]
        sol[#sol + 1] = geo.C[m]
    end
    out[#out + 1] = string.format('    { id = %q, board = %q, name = %q, pegs = %q, goal = %d,\n      sol = { %s } },',
        def.id, def.board, def.name, Geometry.encode(pegs), goal, table.concat(sol, ","))
    ::continue::
end

print("-- Puzzle bank, generated by tools/build_puzzles.lua -- do not edit by hand.")
print("-- pegs: one 0/1 per hole (geometry.lua numbering); goal: the hole the last")
print("-- peg must end in; sol: a checked solution, as from,to hole pairs.")
print("return {")
for _, l in ipairs(out) do print(l) end
print("}")
if failed then os.exit(1) end
